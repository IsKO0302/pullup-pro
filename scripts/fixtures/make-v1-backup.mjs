// Generates tests/fixtures/v1-backup.json with the ORIGINAL PULLUP PRO 1.0 app (legacy/v1/PULLUP-PRO-v1.html):
// onboarding → v1's own demo-data generator → v1's own "export JSON" button. Used by the v1 → v2 import tests.
// usage: node scripts/fixtures/make-v1-backup.mjs   (needs Chromium; CHROMIUM_PATH overrides the binary)
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
const p = await ctx.newPage();
await p.goto('file://' + root + 'legacy/v1/PULLUP-PRO-v1.html');
await p.waitForTimeout(800);
await p.click('label.check:has([data-ob="ok"]) .box');
await p.click('[data-ob="next"]');
await p.fill('[data-ob="name"]', 'Иса');
await p.fill('#ob-max', '6'); await p.dispatchEvent('#ob-max', 'input');
await p.click('[data-ob="next"]');
await p.click('[data-ob="demo"]');
await p.waitForTimeout(800);
await p.evaluate(() => { location.hash = '#/settings'; });
await p.waitForTimeout(600);
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-act="expJson"]')]);
const json = JSON.parse(readFileSync(await dl.path(), 'utf8'));
json._fixture = 'Generated by PULLUP PRO 1.0 (legacy/v1) demo-data generator for automated import tests — not real training data';
writeFileSync(root + 'tests/fixtures/v1-backup.json', JSON.stringify(json, null, 1));
console.log(`v1 backup: version ${json.version}, sessions ${json.data.sessions.length}, tests ${(json.data.tests || []).length}`);
await browser.close();
